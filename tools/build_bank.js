// Build spanish-app/preguntas.js from old reglas.js questions + qbank/*.json + connectors from app.js.
const fs=require('fs'),path=require('path');
const APP=path.resolve(__dirname,'..'), QB=process.env.QBANK||APP+'/qbank';
const r=fs.readFileSync(APP+'/reglas.js','utf8');
const a=r.indexOf('const SE7'), b=r.indexOf("const K='reglas-misses'");
const old=new Function(r.slice(a,b)+';return Q;')();
const appjs=fs.readFileSync(APP+'/app.js','utf8');
const c0=appjs.indexOf('const connectorGroups=['), c1=appjs.indexOf('];',appjs.indexOf("['Conjunciones'",c0))+2;
const CON=new Function(appjs.slice(c0,c1)+';return connectorGroups;')();
const TEMAS=[
 ['se','1. SE','#f0915a','se'],['ser','2. Ser / estar','#6aa8e0','serestar'],['por','3. Por / para','#6cc070','porpara'],['pas','4. Pretérito / imperfecto','#b597e0','pasado'],
 ['sub','5. Subjuntivo','#e07a7a','subj'],['pro','6. Lo / le','#e0b44a','pron'],['gus','7. Gustar','#5cc8d0','gustar'],['gen','8. Género','#f07aae','genero'],
 ['ace','9. Acentos','#a7b4bf','acentos'],['vos','10. Tú, usted y vos','#8f9fe0','vos'],['con','11. Conectores','#e0b44a','conectores'],['prep','12. Preposiciones','#6cc070','prep'],
 ['verbos','13. Verbos que se confunden','#5cc8d0','verbos'],['falsos','14. Falsos amigos','#e07a7a','falsos'],['errores','15. Errores comunes','#f0915a','errores']
].map(([k,name,color,anchor])=>({k,name,color,anchor}));
const P={}, L={}, norm=s=>s.toLowerCase().replace(/\s+/g,' ').trim();
for(const t of TEMAS){
  const seen=new Set(), list=[];
  const add=q=>{ if(!q||!q.s||!Array.isArray(q.o)||!q.o.includes(q.a)) {console.error('BAD',t.k,q&&q.s);return}
    const key=norm(q.s)+'|'+norm(q.a); if(seen.has(key))return; seen.add(key); list.push({s:q.s,o:q.o,a:q.a,w:q.w||''}); };
  old.filter(q=>q.t===t.k).forEach(add);
  const f=QB+'/'+t.k+'.json'; if(fs.existsSync(f)) JSON.parse(fs.readFileSync(f,'utf8')).forEach(add);
  P[t.k]=list;
  const lf=QB+'/libro_'+t.k+'.json'; if(fs.existsSync(lf)) L[t.k]=JSON.parse(fs.readFileSync(lf,'utf8'));
}
const out='// Generated by build_bank.js (11/25/26). Practice questions per topic, book-style typed exercises, connectors.\n'
 +'window.TEMAS='+JSON.stringify(TEMAS)+';\nwindow.PREGUNTAS='+JSON.stringify(P)+';\nwindow.LIBRO='+JSON.stringify(L)+';\nwindow.CONECTORES='+JSON.stringify(CON)+';\n';
fs.writeFileSync(APP+'/preguntas.js',out);
console.log(Object.fromEntries(TEMAS.map(t=>[t.k,P[t.k].length+(L[t.k]?'+'+L[t.k].reduce((x,s)=>x+s.items.length,0):'')])),'bytes',out.length);
